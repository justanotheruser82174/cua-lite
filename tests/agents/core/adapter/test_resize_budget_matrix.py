_DISTINCT_MODEL_BUDGETS = 4
_DISTINCT_BUDGETS_WITH_CANONICAL = 5


@pytest.mark.parametrize("family", sorted(_RESIZE_GOLDENS))
def test_resize_golden_grid(family: str) -> None:
    factor, min_pixels, max_pixels = _FAMILY_BUDGETS[family]
    expected = _RESIZE_GOLDENS[family]
    assert set(expected) == set(_SCREEN_SIZES), f"{family} golden grid drifted"

    actual = {
        (h, w): smart_resize(h, w, factor=factor, min_pixels=min_pixels, max_pixels=max_pixels)
        for h, w in _SCREEN_SIZES
    }
    assert actual == expected, f"{family} resize drift"


@pytest.mark.parametrize("family", sorted(_RESIZE_GOLDENS))
def test_resize_golden_invariants(family: str) -> None:
    factor, _min_pixels, max_pixels = _FAMILY_BUDGETS[family]
    for (h, w), (rh, rw) in _RESIZE_GOLDENS[family].items():
        assert rh % factor == 0 and rw % factor == 0, f"{family} {(h, w)} off-grid"
        assert rh * rw <= max_pixels, f"{family} {(h, w)} over budget"
        assert (rh > rw) == (h > w), f"{family} {(h, w)} orientation flip"


def test_distinct_budgets_across_model_families() -> None:
    model_families = {k: v for k, v in _FAMILY_BUDGETS.items() if k != "canonical"}
    assert len(model_families) == 7
    assert len(set(model_families.values())) == _DISTINCT_MODEL_BUDGETS
    assert len(set(_FAMILY_BUDGETS.values())) == _DISTINCT_BUDGETS_WITH_CANONICAL

    buckets: dict[tuple[int, int, int], list[str]] = {}
    for name, budget in model_families.items():
        buckets.setdefault(budget, []).append(name)
    assert {k: sorted(v) for k, v in buckets.items()} == {
        (28, 3136, 2_007_040): ["qwen2_5_vl"],
        (32, 1024, 6_553_600): ["mai_ui"],
        (28, 3136, 12_845_056): ["fara", "ui_tars_15_v1"],
        (32, 3136, 13_107_200): ["evocua", "qwen3_5", "qwen3_vl"],
    }
    assert sorted({b[2] for b in model_families.values()}) == [
        2_007_040,
        6_553_600,
        12_845_056,
        13_107_200,
    ]
    assert _FAMILY_BUDGETS["canonical"][2] == 1_003_520
